        )
        val slice = StopPlacer.rideSlice(route707, "대전광역시청", "대전역", Coord(36.35120829, 127.38510038), kakaoStops.size)!!
        assertEquals(kakaoStops, slice.map { it.name })
        assertEquals("DJB8001378", slice.first().nodeId)   // 올 때(하행)의 시청 정류장
        assertEquals("DJB8001420", slice.last().nodeId)
    }

    @Test
    fun aStopNameThatAppearsOnBothWaysPicksTheRightDirection() {
        // '시청역'은 갈 때(12번째)·올 때(32번째) 두 번 있다. 올 때 시청역 → 대전역(12곳)을 탄다면
        // 첫 번째 '시청역'부터 세면 32곳이 되어 맞지 않으므로, 정거장 수와 승차 위치가 맞는 쪽을 고른다
        val slice = StopPlacer.rideSlice(route707, "시청역", "대전역", Coord(36.35112, 127.38870), 12)!!
        assertEquals("DJB8002088", slice.first().nodeId)
        assertEquals(12, slice.size)
        // 정거장 수가 전혀 안 맞으면(다른 노선·방향) 쓰지 않는다
        assertNull(StopPlacer.rideSlice(route707, "대전광역시청", "대전역", Coord(36.35120829, 127.38510038), 30))
        // 내릴 곳이 노선에 없으면 null
        assertNull(StopPlacer.rideSlice(route707, "대전광역시청", "유성온천역", Coord(36.3512, 127.3851), 5))
    }
